'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const Brand=require('../scripts/generate-stipra-mark.js');
const Core=require('../src/core.js');
const ROOT=path.resolve(__dirname,'..');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
test('Stiprā mark is generated by real v1 scene engine with three distinct ink passes',()=>{
  const r=Brand.makeRecipe(),scene=Core.resolveRecipe(r);
  assert.equal(scene.format,'stipra-scene');assert.equal(scene.version,1);
  assert.equal(r.inks.length,3);assert.equal(scene.plates.length,3);
  assert.ok(r.layers.length>=750);
  assert.equal(r.substrate.color,'#f4eddf');
  assert.equal(r.canvas.width,480);assert.equal(r.canvas.height,480);
  const svg=Core.renderSvg(scene);
  assert.match(svg,/data-plate="blue-master"/);
  assert.match(svg,/data-plate="coral-master"/);
  assert.match(svg,/data-plate="key-master"/);
  for(const c of ['#227e91','#ee6a4d','#262a3a'])assert.ok(svg.includes(c));
  assert.ok((svg.match(/<circle/g)||[]).length>800);
  assert.doesNotMatch(svg,/<script\b|onload=|xlink:href=|href="https?:\/\//); // SVG namespace is allowed
  assert.notEqual(Core.renderSvg(scene,{plateId:'blue-master'}),Core.renderSvg(scene,{plateId:'coral-master'}));
  assert.equal(r.layers.every(l=>l.coverage===1),true);
});
test('Stiprā logo exports deterministic vector composite, independent masters and normalized recipe',()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'stipra-mark-'));
  try{
    const out=path.join(root,'preview'),first=Brand.generate(out);
    const snapshot=first.manifest.files.map(item=>{
      const data=fs.readFileSync(path.join(out,item.name));
      assert.equal(hash(data),item.sha256,'brand fingerprint mismatch '+item.name);
      assert.equal(data.length,item.bytes);
      return data;
    });
    const second=Brand.generate(out);
    for(let i=0;i<snapshot.length;i++)
      assert.deepEqual(snapshot[i],fs.readFileSync(path.join(out,second.manifest.files[i].name)));
    const composite=fs.readFileSync(path.join(out,'stipra-mark.svg'),'utf8');
    assert.equal(composite,Core.renderSvg(Core.resolveRecipe(Brand.makeRecipe())));
    for(const ink of Brand.COLORS){
      const text=fs.readFileSync(path.join(out,'stipra-mark-'+ink.id+'.svg'),'utf8');
      assert.match(text,/fill="#000000"/);
      assert.match(text,/Uncalibrated preview/);
    }
    assert.match(first.manifest.status,/owner|proposed|unchanged/);
    // Existing owner masthead is not replaced by the unapproved alternate.
    const readme=fs.readFileSync(path.join(ROOT,'README.md'),'utf8');
    assert.match(readme,/src="logo_for_Readme\.svg"/);
    assert.equal(fs.existsSync(path.join(ROOT,'logo_for_Readme.svg')),true);
  }finally{fs.rmSync(root,{force:true,recursive:true});}
});
